/** @type {{id:number,name:string,hanja:string,born:number,died:number,lead:number,navy:number,war:number,int:number,pol:number,cha:number,amb:number,duty:number,comp:number,tags:string[]}[]} */
export const OFFICERS = RAW.trim().split('\n').map((line) => {
  const [head, tagPart] = line.trim().split('#');
  const t = head.trim().split(/\s+/);
  return {
    id: _id++,
    name: t[0], hanja: t[1],
    born: +t[2], died: +t[3],
    lead: +t[4], navy: +t[5], war: +t[6], int: +t[7], pol: +t[8], cha: +t[9],
    amb: +t[10], duty: +t[11], comp: +t[12],
    tags: tagPart ? tagPart.trim().split(',') : [],
  };
});

export const OFFICER_BY_NAME = Object.fromEntries(OFFICERS.map((o) => [o.name, o]));

/** 이름으로 원본 무장 찾기. 없으면 예외 — 시나리오 오타를 조기에 잡는다. */
export function findOfficer(name) {
  const o = OFFICER_BY_NAME[name];
  if (!o) throw new Error(`알 수 없는 무장: ${name}`);
  return o;
}

/** 표시용 이름 — 마충·마충2 처럼 동명이인은 뒤 숫자를 떼고 보여준다 */
export function displayName(o) {
  return o.name.replace(/\d$/, '');
}

/** 종합 능력 — 인재 평가/AI 우선순위용 */
export function overall(o) {
  return Math.round((o.lead * 1.2 + o.war + o.int * 1.2 + o.pol + o.cha * 0.8) / 5.2);
}
